    public void popuniTrenere() {
        try {
            ArrayList<Trener> treneri = ClientController.getInstance()
                    .getAllTrener(new Trener(null, "", "", "", 0));

            cmbTrener.removeAllItems();

            for (Trener trener : treneri) {
                cmbTrener.addItem(trener);
            }

        } catch (Exception ex) {
            Logger.getLogger(FormDetaljiGrupe.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    public void osveziClanoveGrupe() {
        if (!(tblClanovi.getModel() instanceof TableModelClanoviGrupe)) {
            return;
        }
        TableModelClanoviGrupe tm = (TableModelClanoviGrupe) tblClanovi.getModel();
        if (tm.getRowCount() == 0) {
            return;
        }
        try {
            ArrayList<String> uklonjeni = tm.osveziSaServera(g.getKategorija().getKategorijaID());
            osveziIzabranogClana(tm);
            if (!uklonjeni.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Sledeci clanovi su uklonjeni iz grupe jer su obrisani "
                        + "ili vise ne pripadaju kategoriji grupe:\n" + String.join(", ", uklonjeni),
                        "Obavestenje", JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (Exception ex) {
            Logger.getLogger(FormDetaljiGrupe.class.getName()).log(Level.WARNING, "Osvezavanje clanova grupe nije uspelo", ex);
        }
    }

    private void osveziIzabranogClana(TableModelClanoviGrupe tm) {
        if (izabraniClan == null) {
            return;
        }
        for (ClanGrupe cg : tm.getLista()) {
            if (cg.getClan().getClanID().equals(izabraniClan.getClanID())) {
                izabraniClan = cg.getClan();
                txtClan.setText(izabraniClan.getIme() + " " + izabraniClan.getPrezime()
                        + " (" + izabraniClan.getEmail() + ")");
                return;
            }
        }
    }

    private void pokreniOsvezavanje() {
        tajmerOsvezavanja = new javax.swing.Timer(5000, e -> osveziClanoveGrupe());
        tajmerOsvezavanja.start();
    }

    @Override
    public void dispose() {
        if (tajmerOsvezavanja != null) {
            tajmerOsvezavanja.stop();
        }
        super.dispose();
    }

    private void ucitajIzabranuStavku() {
        int row = tblClanovi.getSelectedRow();
        if (row < 0 || !(tblClanovi.getModel() instanceof TableModelClanoviGrupe)) {
            return;
        }
        ClanGrupe cg = ((TableModelClanoviGrupe) tblClanovi.getModel()).getStavka(row);
        izabraniClan = cg.getClan();
        txtClan.setText(izabraniClan.getIme() + " " + izabraniClan.getPrezime()
                + " (" + izabraniClan.getEmail() + ")");
        txtNapomena.setText("/".equals(cg.getNapomena()) ? "" : cg.getNapomena());
    }

    private String procitajNapomenu() {
        String napomena = txtNapomena.getText().trim();
        return napomena.isEmpty() ? "/" : napomena;
    }

    private void ocistiPoljaClana() {
        izabraniClan = null;
        txtClan.setText("");
        txtNapomena.setText("");
        tblClanovi.clearSelection();
    }

