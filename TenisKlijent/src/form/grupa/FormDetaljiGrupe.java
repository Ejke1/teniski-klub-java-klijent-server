    private void btnDodajClanaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajClanaActionPerformed

        if (izabraniClan == null) {
            JOptionPane.showMessageDialog(this, "Izaberite clana klikom na lupu!",
                    "Greska", JOptionPane.ERROR_MESSAGE);
            return;
        }

        TableModelClanoviGrupe tm = (TableModelClanoviGrupe) tblClanovi.getModel();

        if (tm.postojiClan(izabraniClan)) {
            JOptionPane.showMessageDialog(this, "Vec ste uneli ovog clana!");
            return;
        }

        ClanGrupe cg = new ClanGrupe(g, -1, procitajNapomenu(), izabraniClan);
        tm.dodajClana(cg);
        ocistiPoljaClana();

    }//GEN-LAST:event_btnDodajClanaActionPerformed

    private void btnIzmeniClanaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniClanaActionPerformed

        int row = tblClanovi.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Oznacite u tabeli clana kojeg menjate!",
                    "Greska", JOptionPane.ERROR_MESSAGE);
            return;
        }

        FormIzborClana forma = new FormIzborClana(this, true, g.getKategorija());
        forma.setVisible(true);
        Clan noviClan = forma.getIzabraniClan();

        if (noviClan == null) {
            return;
        }

        TableModelClanoviGrupe tm = (TableModelClanoviGrupe) tblClanovi.getModel();

        if (tm.postojiClanOsimReda(noviClan, row)) {
            JOptionPane.showMessageDialog(this, "Ovaj clan je vec u grupi!",
                    "Greska", JOptionPane.ERROR_MESSAGE);
            return;
        }

        tm.izmeniClana(row, noviClan, procitajNapomenu());
        ocistiPoljaClana();
        JOptionPane.showMessageDialog(this, "Clan u stavci " + (row + 1) + " je izmenjen.");

    }//GEN-LAST:event_btnIzmeniClanaActionPerformed

    private void btnObrisiClanaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiClanaActionPerformed

        int row = tblClanovi.getSelectedRow();

        if (row >= 0) {
            TableModelClanoviGrupe tm = (TableModelClanoviGrupe) tblClanovi.getModel();
            tm.obrisiClana(row);
            ocistiPoljaClana();
        } else {
            JOptionPane.showMessageDialog(this, "Izaberite stavku u tabeli koju brisete!",
                    "Greska", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnObrisiClanaActionPerformed

