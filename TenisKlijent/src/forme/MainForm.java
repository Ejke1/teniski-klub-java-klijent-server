    private void pokreniOsvezavanje() {
        tajmerOsvezavanja = new javax.swing.Timer(5000, e -> osveziClanoveGrupe());
        tajmerOsvezavanja.start();
    }

    @Override
    public void dispose() {
        if (tajmerOsvezavanja != null) {
            tajmerOsvezavanja.stop();
        }
        super.dispose();
    }

    private void ucitajIzabranuStavku() {
        int row = tblClanovi.getSelectedRow();
        if (row < 0 || !(tblClanovi.getModel() instanceof TableModelClanoviGrupe)) {
            return;
        }
        ClanGrupe cg = ((TableModelClanoviGrupe) tblClanovi.getModel()).getStavka(row);
        izabraniClan = cg.getClan();
        txtClan.setText(izabraniClan.getIme() + " " + izabraniClan.getPrezime()
                + " (" + izabraniClan.getEmail() + ")");
        txtNapomena.setText("/".equals(cg.getNapomena()) ? "" : cg.getNapomena());
    }

    private String procitajNapomenu() {
        String napomena = txtNapomena.getText().trim();
        return napomena.isEmpty() ? "/" : napomena;
    }

    private void ocistiPoljaClana() {
        izabraniClan = null;
        txtClan.setText("");
        txtNapomena.setText("");
        tblClanovi.clearSelection();
    }

