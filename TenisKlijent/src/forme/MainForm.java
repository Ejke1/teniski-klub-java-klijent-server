    private void btnSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajActionPerformed

        if (txtMaxKapacitet.getText().isEmpty() || txtNaziv.getText().isEmpty()
                || txtOpis.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Sva polja moraju biti popunjena!");
            return;
        }

        try {
            Trener trener = (Trener) cmbTrener.getSelectedItem();
            Kategorija kategorija = (Kategorija) cmbKategorija.getSelectedItem();
            String naziv = txtNaziv.getText();
            String opis = txtOpis.getText();
            int maxKapacitet = Integer.parseInt(txtMaxKapacitet.getText());

            TableModelClanoviGrupe tm = (TableModelClanoviGrupe) tblClanovi.getModel();

            Grupa g = new Grupa(null, naziv, opis, tm.getLista().size(),
                    maxKapacitet, kategorija, trener, ulogovani, tm.getLista());

            setCursor(java.awt.Cursor.getPredefinedCursor(java.awt.Cursor.WAIT_CURSOR));
            String izvestajMail;
            try {
                izvestajMail = ClientController.getInstance().addGrupa(g);
            } finally {
                setCursor(java.awt.Cursor.getDefaultCursor());
            }
            txtNaziv.setText("");
            txtOpis.setText("");
            txtNapomena.setText("");
            txtMaxKapacitet.setText("");
            tm.ocisti();
            ocistiPoljaClana();
            JOptionPane.showMessageDialog(this, "Uspesno sacuvana grupa!\n\n" + izvestajMail);

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da kreira grupu", 
                    "Greska", JOptionPane.ERROR_MESSAGE);
            JOptionPane.showMessageDialog(this, ex.getMessage());
            //            Logger.getLogger(MainForm.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_btnSacuvajActionPerformed

