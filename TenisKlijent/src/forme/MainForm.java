    public void popuniTrenere() {
        try {
            ArrayList<Trener> treneri = ClientController.getInstance()
                    .getAllTrener(new Trener(null, "", "", "", 0));

            cmbTrener.removeAllItems();

            for (Trener trener : treneri) {
                cmbTrener.addItem(trener);
            }

        } catch (Exception ex) {
            Logger.getLogger(MainForm.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    public void popuniKategorije() {
        Object prethodna = cmbKategorija.getSelectedItem();
        ucitavanjeKategorija = true;
        boolean zadrzana = false;
        try {
            ArrayList<Kategorija> kategorije = ClientController.getInstance()
                    .getAllKategorija(new Kategorija(null, "", ""));

            cmbKategorija.removeAllItems();

            for (Kategorija kategorija : kategorije) {
                cmbKategorija.addItem(kategorija);
                if (prethodna instanceof Kategorija && kategorija.getKategorijaID()
                        .equals(((Kategorija) prethodna).getKategorijaID())) {
                    cmbKategorija.setSelectedItem(kategorija);
                    zadrzana = true;
                }
            }

        } catch (Exception ex) {
            Logger.getLogger(MainForm.class.getName()).log(Level.SEVERE, null, ex);
        } finally {
            ucitavanjeKategorija = false;
        }

        if (!zadrzana && tblClanovi.getModel() instanceof TableModelClanoviGrupe) {
            ((TableModelClanoviGrupe) tblClanovi.getModel()).ocisti();
            ocistiPoljaClana();
        }
    }

    public void osveziClanoveGrupe() {
        if (!(tblClanovi.getModel() instanceof TableModelClanoviGrupe)) {
            return;
        }
        TableModelClanoviGrupe tm = (TableModelClanoviGrupe) tblClanovi.getModel();
        if (tm.getRowCount() == 0) {
            return;
        }
        try {
            ArrayList<String> uklonjeni = tm.osveziSaServera(cmbKategorija.getSelectedItem() instanceof Kategorija
                    ? ((Kategorija) cmbKategorija.getSelectedItem()).getKategorijaID() : null);
            osveziIzabranogClana(tm);
            if (!uklonjeni.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Sledeci clanovi su uklonjeni iz grupe jer su obrisani "
                        + "ili vise ne pripadaju kategoriji grupe:\n" + String.join(", ", uklonjeni),
                        "Obavestenje", JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (Exception ex) {
            Logger.getLogger(MainForm.class.getName()).log(Level.WARNING, "Osvezavanje clanova grupe nije uspelo", ex);
        }
    }

    private void osveziIzabranogClana(TableModelClanoviGrupe tm) {
        if (izabraniClan == null) {
            return;
        }
        for (ClanGrupe cg : tm.getLista()) {
            if (cg.getClan().getClanID().equals(izabraniClan.getClanID())) {
                izabraniClan = cg.getClan();
                txtClan.setText(izabraniClan.getIme() + " " + izabraniClan.getPrezime()
                        + " (" + izabraniClan.getEmail() + ")");
                return;
            }
        }
    }

