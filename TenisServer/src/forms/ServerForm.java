    private void azurirajProgressBar() {
        int ispunjenost = 0;

        if (cbVerifikacija.isSelected()) {
            ispunjenost+=25;
        }
        if (cbSinhronizacija.isSelected()) {
            ispunjenost+=25;
        }
        if (cbEvidencija.isSelected()){
            ispunjenost+=25;
        }
        String pin = String.copyValueOf(txtPIN.getPassword());
        if (pin.equals(pinS)) {
            ispunjenost+=25;
        }
        
        progressBar.setValue(ispunjenost);
        btnPokreniServer.setEnabled(ispunjenost==100);
}
    
