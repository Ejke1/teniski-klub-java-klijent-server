    private void btnPokreniServerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPokreniServerActionPerformed
            
            if (threadServer == null || !threadServer.isAlive()) {
                threadServer = new ThreadServer();
                if (threadServer.getServerSocket() == null) {
                    JOptionPane.showMessageDialog(this, "Server nije pokrenut jer je port zauzet. Proverite da li je server vec pokrenut.",
                            "Greska", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                threadServer.start();
                lblServerStatus.setText("Aktivan");
                lblLampa.setBackground(Color.GREEN);
                btnUgasiServer.setEnabled(true);
                btnPokreniServer.setEnabled(false);
                cbVerifikacija.setEnabled(false);
                cbSinhronizacija.setEnabled(false);
                cbEvidencija.setEnabled(false);
                txtPIN.setEnabled(false);
            }
         
    }//GEN-LAST:event_btnPokreniServerActionPerformed

